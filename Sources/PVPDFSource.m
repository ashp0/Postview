// A number no other shared-memory segment in this process will use.
//
// Process-global rather than per-source, which is what lets the NAME drop the
// source pointer: the pointer was there to disambiguate two sources using the
// same counter, and it cost 12 of the 31 characters available. Atomic because
// two render lanes reach this concurrently.
static uint64_t PVNextSharedMemoryToken(void)
{
    static volatile int64_t counter;
    return (uint64_t)__sync_add_and_fetch(&counter, 1);
}

typedef struct {
    void *address;
    size_t length;
} PVSharedBitmap;

static void PVReleaseSharedBitmap(void *info, const void *data, size_t size)
{
    PVSharedBitmap *bitmap = (PVSharedBitmap *)info;
    if (bitmap) {
        if (bitmap->address && bitmap->length)
            munmap(bitmap->address, bitmap->length);
        free(bitmap);
    }
}

static BOOL PVWriteExact(int fd, const void *bytes, size_t length)
{
    size_t offset = 0;
    while (offset < length) {
        ssize_t count = write(fd, (const char *)bytes + offset, length - offset);
        if (count < 0 && errno == EINTR) continue;
        if (count <= 0) return NO;
        offset += (size_t)count;
    }
    return YES;
}

// Read exactly `length` bytes, or give up at `deadline`.
//
// `outTimedOut` separates the two ways this returns NO, and they are not the
// same failure: a deadline means the helper is wedged inside Quartz and is
// worth another try with a fresh process, while EOF means it is gone. The
// caller has to be able to tell them apart -- see PVRenderFailure.
static BOOL PVReadExactUntil(int fd, void *bytes, size_t length, double deadline,
                             BOOL *outTimedOut)
{
    size_t offset = 0;
    if (outTimedOut) *outTimedOut = NO;
    while (offset < length) {
        double left = deadline - PVMonotonicSeconds();
        if (!(left > 0)) { if (outTimedOut) *outTimedOut = YES; return NO; }
        int milliseconds = (left > 60.0) ? 60000 : (int)ceil(left * 1000.0);
        if (milliseconds < 1) milliseconds = 1;
        struct pollfd item;
        item.fd = fd;
        item.events = POLLIN | POLLHUP | POLLERR;
        item.revents = 0;
        int ready;
        do { ready = poll(&item, 1, milliseconds); }
        while (ready < 0 && errno == EINTR);
        if (ready == 0) { if (outTimedOut) *outTimedOut = YES; return NO; }
        if (ready < 0 || (item.revents & (POLLERR | POLLNVAL))) return NO;

        ssize_t count = read(fd, (char *)bytes + offset, length - offset);
        if (count < 0 && errno == EINTR) continue;
        if (count <= 0) return NO;
        offset += (size_t)count;
    }
    return YES;
}

