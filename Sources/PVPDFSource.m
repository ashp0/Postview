- (NSString *)renderHelperPath
{
    NSString *directory = [[[NSBundle mainBundle] executablePath]
        stringByDeletingLastPathComponent];
    return [directory stringByAppendingPathComponent:@"PostviewRenderHelper"];
}

// Kill the helper and reap it. Safe from any thread, and safe from -dealloc:
// no run loop is spun and no Objective-C object is involved.
//
// The pipes are closed first. A helper blocked in read() sees EOF and exits on
// its own; SIGKILL then covers the one that is wedged inside Quartz, which is
// the entire reason this process exists. waitpid without WNOHANG is bounded
// because SIGKILL is uncatchable -- the child cannot decline it, and it is
// already dead or dying by the time this waits.
- (void)stopRenderHelper
{
    if (_helperIn  >= 0) { close(_helperIn);  _helperIn  = -1; }
    if (_helperOut >= 0) { close(_helperOut); _helperOut = -1; }

    if (_helperPid > 0) {
        (void)kill(_helperPid, SIGKILL);
        int status = 0;
        pid_t reaped;
        do { reaped = waitpid(_helperPid, &status, 0); }
        while (reaped < 0 && errno == EINTR);
        _helperPid = 0;
    }
    _helperRenders = 0;
}

- (BOOL)startHelperWithGeometry:(BOOL)wantGeometry
                          reply:(PVRenderOpenReply *)outReply
                        failure:(PVRenderFailure *)outFailure
{
    PVRenderFailure ignored;
    if (!outFailure) outFailure = &ignored;
    *outFailure = PVRenderFailureNone;
    [self stopRenderHelper];

    NSString *helperPath = [self renderHelperPath];
    if (![[NSFileManager defaultManager] isExecutableFileAtPath:helperPath]) {
        _helperUnavailable = YES;
        *outFailure = PVRenderFailureHelperUnavailable;
        return NO;
    }

    // A helper that dies mid-command turns the next write into SIGPIPE, which
    // would take the whole viewer down for the one failure this design exists
    // to contain. Ignored process-wide; the write returns EPIPE instead and the
    // render is reported as failed.
    static dispatch_once_t ignoreBrokenPipeOnce;
    dispatch_once(&ignoreBrokenPipeOnce, ^{ signal(SIGPIPE, SIG_IGN); });

    int toHelper[2]   = { -1, -1 };
    int fromHelper[2] = { -1, -1 };
    posix_spawn_file_actions_t actions;
    posix_spawnattr_t attr;
    BOOL actionsReady = NO, attrReady = NO;
    pid_t pid = 0;

    if (pipe(toHelper) != 0)   goto failed;
    if (pipe(fromHelper) != 0) goto failed;

    if (posix_spawn_file_actions_init(&actions) != 0) goto failed;
    actionsReady = YES;

    // Only the two pipe ends the helper needs, plus a null stderr. Everything
    // else this process holds -- the snapshot, the state store, the window
    // server connection -- is closed in the child by POSIX_SPAWN_CLOEXEC_DEFAULT
    // below, so a helper that is killed cannot be holding anything open.
    if (posix_spawn_file_actions_adddup2(&actions, toHelper[0], STDIN_FILENO) != 0 ||
        posix_spawn_file_actions_adddup2(&actions, fromHelper[1], STDOUT_FILENO) != 0 ||
        posix_spawn_file_actions_addopen(&actions, STDERR_FILENO,
                                         "/dev/null", O_WRONLY, 0) != 0)
        goto failed;

    if (posix_spawnattr_init(&attr) != 0) goto failed;
    attrReady = YES;
    // Checked, not discarded. Without POSIX_SPAWN_CLOEXEC_DEFAULT the child
    // inherits every descriptor this process holds -- the snapshot, the state
    // store's lock, the window server connection -- and a helper killed while
    // wedged would take those open descriptors with it into the grave. A
    // silently ignored failure here is a containment property silently lost.
    if (posix_spawnattr_setflags(&attr, POSIX_SPAWN_CLOEXEC_DEFAULT) != 0)
        goto failed;

    {
        char *argv[4];
        argv[0] = (char *)[helperPath fileSystemRepresentation];
        argv[1] = (char *)[[_snapshot path] fileSystemRepresentation];
        argv[2] = (char *)(wantGeometry ? PV_HELPER_MODE_META
                                        : PV_HELPER_MODE_RENDER);
        argv[3] = NULL;
        int rc = posix_spawn(&pid, argv[0], &actions, &attr, argv, NULL);
        if (rc != 0) { pid = 0; goto failed; }
    }

    // Not cleared afterwards: nothing below this point can reach `failed`, so a
    // second destroy is unreachable rather than guarded against. Assigning the
    // flags here would be a store the analyser correctly reports as dead.
    posix_spawnattr_destroy(&attr);
    posix_spawn_file_actions_destroy(&actions);

    // The child's ends, closed in the parent: without this the parent holds the
    // write end of its own read pipe and never sees EOF when the helper dies.
    close(toHelper[0]);   toHelper[0] = -1;
    close(fromHelper[1]); fromHelper[1] = -1;

    (void)fcntl(toHelper[1],  F_SETFD, FD_CLOEXEC);
    (void)fcntl(fromHelper[0], F_SETFD, FD_CLOEXEC);

    _helperPid = pid;
    _helperIn  = toHelper[1];
    _helperOut = fromHelper[0];
    _helperRenders = 0;

    {
        // The open reply, before this helper is considered started at all. It
        // arrives under its own deadline for the same reason every other
        // exchange does: the helper may be parsing something that never ends.
        PVRenderOpenReply reply;
        memset(&reply, 0, sizeof(reply));
        BOOL timedOut = NO;
        double deadline = PVMonotonicSeconds() + PV_OPEN_DEADLINE_SECONDS;
        BOOL got = PVReadExactUntil(_helperOut, &reply, sizeof(reply),
                                    deadline, &timedOut);
        if (!got || reply.magic != PV_RENDER_PROTOCOL_MAGIC ||
            reply.version != PV_RENDER_PROTOCOL_VERSION) {
            [self stopRenderHelper];
            *outFailure = !got && timedOut ? PVRenderFailureTimeout
                        : !got             ? PVRenderFailureHelperUnavailable
                                           : PVRenderFailureProtocol;
            return NO;
        }
        if (outReply) *outReply = reply;
    }
    return YES;

failed:
    if (attrReady)    posix_spawnattr_destroy(&attr);
    if (actionsReady) posix_spawn_file_actions_destroy(&actions);
    if (toHelper[0]   >= 0) close(toHelper[0]);
    if (toHelper[1]   >= 0) close(toHelper[1]);
    if (fromHelper[0] >= 0) close(fromHelper[0]);
    if (fromHelper[1] >= 0) close(fromHelper[1]);
    if (pid > 0) {
        (void)kill(pid, SIGKILL);
        int status = 0;
        pid_t reaped;
        do { reaped = waitpid(pid, &status, 0); }
        while (reaped < 0 && errno == EINTR);
    }
    // A resource failure, not a broken installation. Everything reaching this
    // label is a pipe that could not be made, a spawn_file_actions that could
    // not be initialised, or a posix_spawn that could not fork -- all of them
    // things a machine briefly out of descriptors or process slots does, and
    // all of them worth trying again. The helper being MISSING is answered far
    // above, before any of this is attempted, and that one is permanent.
    *outFailure = PVRenderFailureTransientResource;
    return NO;
}

// A helper ready to take a render command, starting one if the last was killed
// or retired.
- (BOOL)ensureRenderHelper:(PVRenderFailure *)outFailure
{
    if (_helperPid > 0 && _helperIn >= 0 && _helperOut >= 0) return YES;
    if (_helperUnavailable) {
        *outFailure = PVRenderFailureHelperUnavailable;
        return NO;
    }

    PVRenderOpenReply reply;
    memset(&reply, 0, sizeof(reply));
    if (![self startHelperWithGeometry:NO reply:&reply failure:outFailure])
        return NO;
    // The replacement has to be looking at the same document the geometry was
    // measured from. It is the same snapshot bytes, so a disagreement here
    // means the snapshot is gone or damaged, and no page will render again.
    if (reply.status != PVRenderOpenOK ||
        reply.pageCount != (uint64_t)_pageCount) {
        [self stopRenderHelper];
        *outFailure = PVRenderFailureProtocol;
        return NO;
    }
    return YES;
}

// What the helper's reply status means about whether this is worth retrying.
static PVRenderFailure PVFailureForReplyStatus(int32_t status)
{
    switch (status) {
        // The renderer declined this page: a page object the document would not
        // hand back, or a bitmap context Quartz refused to build over a buffer
        // it had already been told the shape of. Deterministic.
        case EINVAL:  return PVRenderFailureInvalidPage;
        case EPROTO:  return PVRenderFailureProtocol;
        // Everything else is an errno from shm_open or mmap inside the helper:
        // a resource that was not available at that instant.
        default:      return PVRenderFailureTransientResource;
    }
}

