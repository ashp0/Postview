// Deliberately no PVRenderCore.h and no <CoreGraphics/CGPDFDocument.h> use.
// This process does not open PDFs. See PVPDFSource.h.

// The largest source document this viewer will copy, and the free space it
// insists on having left over afterwards.
//
// Neither bound existed, and the copy loop below reads until EOF. A sparse
// regular file is the cheap way to demonstrate the problem -- a hundred
// gigabytes of holes costs nothing to create and fills the boot volume when
// copied -- but any large regular file does it, and the temporary directory
// filling up takes the rest of the system with it, not just Postview. Two
// gigabytes is far past any PDF that can be presented on the target hardware.
#define PV_MAX_PDF_BYTES     (2LL * 1024LL * 1024LL * 1024LL)
#define PV_SNAPSHOT_HEADROOM (256LL * 1024LL * 1024LL)

// Renders one helper serves before it is retired and replaced.
//
// Quartz accumulates parsed content inside a CGPDFDocumentRef -- fonts, shading
// dictionaries, decoded images -- and never gives it back while the document is
// open. Measured at 183-242 MB of helper RSS against 34-40 MB in the viewer,
// which the soak gate could not see because it only ever looked at
// mach_task_self(). The process boundary that contains the faults is also the
// only lever that reclaims this: a fresh helper starts at nothing.
//
// Retired between renders, chosen by the viewer, so a recycle never turns into
// a failed page. A frame this large is worth recycling for on its own: it is a
// zoomed page whose parse cost is already paid and whose peak is the thing the
// budget cannot absorb twice.
#define PV_HELPER_MAX_RENDERS  128
#define PV_HELPER_LARGE_FRAME  (64ULL * 1024ULL * 1024ULL)

static NSError *PVError(NSInteger code, NSString *desc, NSString *reason)
{
    NSMutableDictionary *info = [NSMutableDictionary dictionary];
    if (desc)   [info setObject:desc   forKey:NSLocalizedDescriptionKey];
    if (reason) [info setObject:reason forKey:NSLocalizedRecoverySuggestionErrorKey];
    return [NSError errorWithDomain:@"PostviewErrorDomain" code:code userInfo:info];
}

// The largest page dimension the layout maths is willing to carry, in points.
// The PDF format's own limit is 14400 pt (200 in); anything past this is either
// corrupt or generated by something that did not read the spec.
#define PV_MAX_PAGE_POINTS  20000.0

// The longest name shm_open will accept, including the leading slash.
//
// This is PSHMNAMLEN, and it is 31 -- not PATH_MAX, and not the 96-byte field
// the protocol carries the name in. A longer name is refused outright with
// ENAMETOOLONG, so a naming scheme that grows with a counter stops working
// partway through a session rather than never working: measured, the previous
// scheme ("/postview-<pid>-<pointer>-<counter>") fitted for the first 99
// renders of a source and failed for every render after that, permanently,
// with the pages simply staying blank.
#define PV_SHM_NAME_MAX 31

// A page size layout can work with, preserving the page's shape.
//
// The two axes are clamped TOGETHER. They used to be clamped independently --
// each axis that was degenerate or past the ceiling was replaced with the
// corresponding US Letter dimension -- and for a page that failed on one axis
// only, that invents an aspect ratio the document does not have. A 25000 x 300
// pt banner became a 612 x 300 pt page: the renderer then fits the real crop
// box into that frame, which preserves aspect and so draws the banner as a
// 612 x 7 pt strip marooned in a 612 x 300 pt page, with the rest of the frame
// blank. The page is not distorted but it is the wrong page, and nothing
// anywhere says so.
//
// Scaling both axes by one factor keeps the shape, so the oversized page is
// simply presented smaller -- which is what a viewer should do with a page too
// large to lay out. Only a size that is degenerate in a way no scale can fix
// (non-finite, or not positive on both axes) falls back to US Letter, and that
// is a page with no geometry rather than one with too much.
static CGSize PVUsablePageSize(CGSize s)
{
    if (!isfinite(s.width) || !isfinite(s.height) ||
        !(s.width > 1) || !(s.height > 1))
        return CGSizeMake(612, 792);

    double k = 1.0;
    if (s.width  > PV_MAX_PAGE_POINTS) k = PV_MAX_PAGE_POINTS / (double)s.width;
    if (s.height > PV_MAX_PAGE_POINTS) {
        double kh = PV_MAX_PAGE_POINTS / (double)s.height;
        if (kh < k) k = kh;
    }
    if (k >= 1.0) return s;

    CGSize out = CGSizeMake((CGFloat)((double)s.width * k),
                            (CGFloat)((double)s.height * k));
    // The scale cannot make either axis degenerate -- both were above 1 and the
    // factor is the ratio of the ceiling to the larger of them -- but the floor
    // is stated rather than reasoned about, because everything downstream
    // divides by these.
    if (!(out.width  > 1) || !isfinite(out.width))  out.width  = 1;
    if (!(out.height > 1) || !isfinite(out.height)) out.height = 1;
    return out;
}

@interface PVPDFSnapshot : NSObject {
    NSString *_path;
    // Held open for the snapshot's whole life, carrying a shared advisory lock
    // and nothing else. It is never read or written through. See
    // PVSweepAbandonedSnapshots.
    int       _lockFD;
}
- (id)initWithSourceURL:(NSURL *)url error:(NSError **)outError;
- (NSString *)path;
@end

// The prefix every snapshot's name begins with. One definition, because a
// sweeper that disagreed with the maker about the name would either delete
// nothing or delete something else.
#define PV_SNAPSHOT_PREFIX "Postview-PDF-"

// Snapshots left behind by processes that are gone.
//
// A snapshot is unlinked in -dealloc, which covers every ordinary exit and none
// of the others: kill -9, a crash, a power cut. Measured on the development
// machine after a day of testing -- 41 abandoned files, ~100 MB. The system
// does eventually reap its temporary directory, but "eventually" is not a
// bound, and a reader who crashes twice a week accumulates.
//
// Whether a file is abandoned is asked, not guessed. Every live snapshot holds
// a shared advisory lock on its own file for as long as it exists, so a file
// that will accept an exclusive lock is a file no live snapshot is using. That
// is exact, unlike an age heuristic, which would eventually delete the snapshot
// of a document somebody has had open all week.
//
// The age test is kept as well, and only as a courtesy to a DIFFERENT build:
// a Postview old enough not to take the lock would otherwise have its snapshot
// swept while it was still reading it. An hour is far longer than the window
// between making a snapshot and opening it.
#define PV_SNAPSHOT_STALE_SECONDS (3600.0)

static void PVSweepAbandonedSnapshots(void)
{
    NSString *directory = NSTemporaryDirectory();
    if (![directory length]) return;

    NSFileManager *fm = [NSFileManager defaultManager];
    NSArray *names = [fm contentsOfDirectoryAtPath:directory error:NULL];
    NSString *prefix = [NSString stringWithUTF8String:PV_SNAPSHOT_PREFIX];
    NSUInteger i, n = [names count];
    for (i = 0; i < n; i++) {
        NSString *name = [names objectAtIndex:i];
        if (![name isKindOfClass:[NSString class]]) continue;
        if (![name hasPrefix:prefix]) continue;

        NSString *path = [directory stringByAppendingPathComponent:name];
        const char *fsPath = [path fileSystemRepresentation];
        int fd = open(fsPath, O_RDONLY);
        if (fd < 0) continue;

        struct stat info;
        BOOL old = (fstat(fd, &info) == 0 && S_ISREG(info.st_mode) &&
                    (time(NULL) - info.st_mtimespec.tv_sec) >
                        (time_t)PV_SNAPSHOT_STALE_SECONDS);
        // The exclusive lock is the question and the answer both: taking it
        // proves nothing else holds it, and holding it means nothing else can
        // start using the file between here and the unlink.
        if (old && flock(fd, LOCK_EX | LOCK_NB) == 0) {
            unlink(fsPath);
            flock(fd, LOCK_UN);
        }
        close(fd);
    }
}

void PVSweepAbandonedSnapshotsNow(void)
{
    PVSweepAbandonedSnapshots();
}

@implementation PVPDFSnapshot

// Why the snapshot stays a named file on disk, rather than an unlinked
// descriptor passed to helpers.
//
// An anonymous already-unlinked file would be crash-clean -- nothing survives
// the process -- and that was tried. It does not work here, for a reason worth
// recording so it is not tried again: on Darwin, opening /dev/fd/N is a dup(),
// not a fresh open. Every helper handed the same descriptor would share ONE
// file offset with every other helper and with this process. Two render lanes
// and the thumbnail source seeking concurrently through one shared offset is
// not a tidiness question, it is torn reads of the document, and Quartz gives
// no assurance it reads by pread rather than lseek. Verified experimentally,
// not assumed: seeking a /dev/fd/N descriptor moves the original's offset.
//
// So the file keeps a name, each helper does its own independent open(), and
// the residue of a crash is one file in NSTemporaryDirectory, which the system
// reaps. That is the smaller of the two prices.
- (id)initWithSourceURL:(NSURL *)url error:(NSError **)outError
{
    self = [super init];
    if (!self) return nil;
    _lockFD = -1;

    // Once per process, and here rather than at launch: this is the moment a
    // temporary directory full of abandoned copies actually costs something,
    // and it keeps the sweep out of the path of an app that never opens a file.
    static dispatch_once_t sweepOnce;
    dispatch_once(&sweepOnce, ^{ PVSweepAbandonedSnapshots(); });

    NSString *pattern = [NSTemporaryDirectory()
        stringByAppendingPathComponent:@"" PV_SNAPSHOT_PREFIX "XXXXXX"];
    char *tmp = strdup([pattern fileSystemRepresentation]);
    void *buffer = NULL;
    int input = -1, output = -1, saved = 0;
    long long copied = 0;
    struct stat before, after;
    struct statfs space;
    memset(&before, 0, sizeof(before));
    memset(&after, 0, sizeof(after));

    if (!tmp) { saved = ENOMEM; goto failed; }
    input = open([[[url path] stringByStandardizingPath] fileSystemRepresentation],
                 O_RDONLY);
    if (input < 0) { saved = errno; goto failed; }
    (void)fcntl(input, F_SETFD, FD_CLOEXEC);
    // The two failures are separated because only one of them sets errno.
    // fstat succeeding on something that is not a regular file leaves errno
    // holding whatever the last unrelated call left there -- or nothing at all,
    // which is an undefined read -- and the error the user is then shown is a
    // strerror() of that.
    if (fstat(input, &before) != 0) { saved = errno; goto failed; }
    if (!S_ISREG(before.st_mode))   { saved = EINVAL; goto failed; }
    // Bounded before a single byte is read, not discovered partway through.
    if (before.st_size < 0 || (long long)before.st_size > PV_MAX_PDF_BYTES) {
        saved = EFBIG;
        goto failed;
    }

    output = mkstemp(tmp);
    if (output < 0) { saved = errno; goto failed; }
    (void)fcntl(output, F_SETFD, FD_CLOEXEC);
    (void)fchmod(output, S_IRUSR | S_IWUSR);

    // Filling the volume is not Postview's failure to have alone: everything
    // else on the machine is writing to the same disk. Asked once, of the
    // volume the temporary file actually landed on rather than of the path it
    // was requested at.
    if (fstatfs(output, &space) == 0) {
        long long available = (long long)space.f_bavail * (long long)space.f_bsize;
        if (available < (long long)before.st_size + PV_SNAPSHOT_HEADROOM) {
            saved = ENOSPC;
            goto failed;
        }
    }

    buffer = malloc(128 * 1024);
    if (!buffer) { saved = ENOMEM; goto failed; }
    for (;;) {
        ssize_t got;
        do { got = read(input, buffer, 128 * 1024); }
        while (got < 0 && errno == EINTR);
        if (got < 0) { saved = errno; goto failed; }
        if (got == 0) break;

        // The bound again, this time against what is actually arriving. fstat
        // reported a size; a file being appended to, or one whose size the
        // filesystem misreports, can still deliver more than that, and the
        // ceiling has to hold against the bytes rather than against the claim.
        copied += (long long)got;
        if (copied > PV_MAX_PDF_BYTES) { saved = EFBIG; goto failed; }

        ssize_t offset = 0;
        while (offset < got) {
            ssize_t put;
            do { put = write(output, (char *)buffer + offset,
                             (size_t)(got - offset)); }
            while (put < 0 && errno == EINTR);
            if (put <= 0) { saved = errno ? errno : EIO; goto failed; }
            offset += put;
        }
    }
    if (fstat(input, &after) != 0) { saved = errno; goto failed; }
    // st_ctimespec as well as st_mtimespec: a rename, a permission change or a
    // truncation-and-rewrite that lands on the same mtime still moves ctime,
    // and any of them means the bytes just copied are not one coherent file.
    if (before.st_dev != after.st_dev || before.st_ino != after.st_ino ||
        before.st_size != after.st_size ||
        before.st_mtimespec.tv_sec != after.st_mtimespec.tv_sec ||
        before.st_mtimespec.tv_nsec != after.st_mtimespec.tv_nsec ||
        before.st_ctimespec.tv_sec != after.st_ctimespec.tv_sec ||
        before.st_ctimespec.tv_nsec != after.st_ctimespec.tv_nsec) {
        saved = EBUSY;
        goto failed;
    }
    // What was actually copied, against what was promised. The size comparison
    // above comes from two fstats of the same descriptor; this one is the only
    // check that the copy loop itself moved the whole file.
    if (copied != (long long)after.st_size) { saved = EBUSY; goto failed; }

    // No fsync.
    //
    // It was here, and it bought nothing: this file is deleted when the
    // document closes, so it has no durability requirement whatsoever -- there
    // is no state worth surviving a power cut in a copy whose entire purpose is
    // to be thrown away. What it cost was a blocking flush of up to two
    // gigabytes on the thread opening the document, and, on a network volume
    // that went away mid-open, an indefinite hang in the one call that cannot
    // be given a deadline.

    // -[NSFileManager stringWithFileSystemRepresentation:length:] is the one
    // that exists; the NSString spelling of it does not, and resolved to a
    // guessed `id` return at compile time.
    _path = [[[NSFileManager defaultManager]
        stringWithFileSystemRepresentation:tmp length:strlen(tmp)] copy];
    if (!_path) { saved = ENOMEM; goto failed; }

    // The claim on this file, held until -dealloc. Shared rather than
    // exclusive, so several snapshots of the same document -- which cannot
    // happen, but the lock should not be the thing that decides that -- and,
    // more usefully, so the sweeper's LOCK_EX is the only thing that ever
    // conflicts. A failure to take it is not fatal: the worst case is that a
    // future sweep reclaims this file an hour early, and refusing to open the
    // document over it would be far worse.
    _lockFD = dup(output);
    if (_lockFD >= 0) {
        (void)fcntl(_lockFD, F_SETFD, FD_CLOEXEC);
        if (flock(_lockFD, LOCK_SH | LOCK_NB) != 0) {
            close(_lockFD);
            _lockFD = -1;
        }
    }

    free(buffer);
    close(input);
    close(output);
    free(tmp);
    return self;

failed:
    if (buffer) free(buffer);
    if (input >= 0) close(input);
    if (output >= 0) close(output);
    if (tmp) {
        unlink(tmp);
        free(tmp);
    }
    if (outError) {
        NSString *reason;
        if (saved == EFBIG) {
            reason = @"It is larger than the two gigabytes Postview will copy "
                     @"before opening a document.";
        } else if (saved == ENOSPC) {
            reason = @"There is not enough free space to copy it safely.";
        } else {
            reason = [NSString stringWithFormat:
                @"The source changed or became unreadable (%s).",
                strerror(saved ? saved : EIO)];
        }
        *outError = PVError(8, @"This PDF could not be copied safely.", reason);
    }
    [self release];
    return nil;
}

- (NSString *)path { return _path; }

- (void)dealloc
{
    if (_path) unlink([_path fileSystemRepresentation]);
    // After the unlink, so the lock is held across it and a sweep running in
    // another process cannot get between the two.
    if (_lockFD >= 0) { flock(_lockFD, LOCK_UN); close(_lockFD); _lockFD = -1; }
    [_path release];
    [super dealloc];
}

