- (CGImageRef)createImageForPage:(NSUInteger)index
                       pixelSize:(CGSize)px
                     interactive:(BOOL)interactive
                         failure:(PVRenderFailure *)failure
{
    PVRenderFailure ignored;
    if (!failure) failure = &ignored;
    *failure = PVRenderFailureNone;

    if (index >= _pageCount) { *failure = PVRenderFailureInvalidPage; return NULL; }
    CGSize use = PVClampPixelSize(px);
    if (!(use.width >= 1) || !(use.height >= 1)) {
        *failure = PVRenderFailureInvalidPage;
        return NULL;
    }

    size_t width = (size_t)use.width;
    size_t height = (size_t)use.height;
    if (width > (SIZE_MAX - 63) / 4) { *failure = PVRenderFailureInvalidPage; return NULL; }
    size_t bytesPerRow = (width * 4 + 63) & ~(size_t)63;
    if (height > SIZE_MAX / bytesPerRow) { *failure = PVRenderFailureInvalidPage; return NULL; }
    size_t bytes = bytesPerRow * height;

    if (![self ensureRenderHelper:failure]) return NULL;

    // Both parts in hex and nothing else. A pid is at most 5 hex digits and the
    // token at most 16, so the longest name this can produce is
    // "/pv-" + 5 + "-" + 16 = 26 characters, comfortably inside
    // PV_SHM_NAME_MAX for the life of the process. See PV_SHM_NAME_MAX for what
    // went wrong when the name could outgrow it.
    char name[PV_RENDER_SHM_NAME_MAX + 1];
    int sharedFD = -1;
    unsigned attempt;
    for (attempt = 0; attempt < 16; attempt++) {
        _helperSequence = PVNextSharedMemoryToken();
        int written = snprintf(name, sizeof(name), "/pv-%x-%llx",
                               (unsigned)getpid(),
                               (unsigned long long)_helperSequence);
        // Stated rather than assumed. If the arithmetic above is ever wrong,
        // this fails one render loudly instead of failing every render for the
        // rest of the session in a way that looks like a blank document.
        if (written < 0 || (size_t)written >= sizeof(name)) {
            *failure = PVRenderFailureProtocol;
            return NULL;
        }
        sharedFD = shm_open(name, O_CREAT | O_EXCL | O_RDWR, 0600);
        if (sharedFD >= 0 || errno != EEXIST) break;
    }
    if (sharedFD < 0) { *failure = PVRenderFailureTransientResource; return NULL; }
    (void)fcntl(sharedFD, F_SETFD, FD_CLOEXEC);
    if (ftruncate(sharedFD, (off_t)bytes) != 0) {
        close(sharedFD); shm_unlink(name);
        *failure = PVRenderFailureTransientResource;
        return NULL;
    }

    // PROT_READ, and no memset.
    //
    // Both halves of that are the same decision. The viewer used to map the
    // segment writable and zero every byte of it before handing the name over,
    // which did two unwanted things: it made this process touch every page of a
    // ~28 MB mapping, so a deferred backing-store failure raised SIGBUS HERE --
    // in the process the helper exists to keep alive -- and it doubled the
    // memory traffic of every full-resolution render for bytes the helper
    // overwrites in full a moment later. PVRenderPDFPageToBuffer fills the whole
    // bitmap with white before it draws, and ftruncate guarantees the row
    // padding it does not reach is already zero.
    //
    // Read-only here also states the direction of the channel: the helper
    // writes pixels, the viewer reads them, and neither needs the other's
    // permission.
    void *map = mmap(NULL, bytes, PROT_READ, MAP_SHARED, sharedFD, 0);
    close(sharedFD);
    if (map == MAP_FAILED) {
        shm_unlink(name);
        *failure = PVRenderFailureTransientResource;
        return NULL;
    }

    PVResidentAdd(PVResidentRender, bytes);

    // Everything from here to the @finally is bracketed, because the resident
    // accounting and the mapping are both live across it. The old in-process
    // renderer had the same shape without the bracket: an Objective-C exception
    // raised after PVResidentAdd unwound straight past the release, leaking the
    // buffer and leaving the render bucket permanently overstated -- which then
    // shrank every later render's budget for the rest of the session.
    //
    // `map` is handed to the returned image on the success path, so ownership of
    // it moves to `handed` rather than being released here.
    CGImageRef image = NULL;
    BOOL handed = NO;
    BOOL retire = NO;
    @try {
        PVRenderCommand command;
        memset(&command, 0, sizeof(command));
        command.magic = PV_RENDER_PROTOCOL_MAGIC;
        command.version = PV_RENDER_PROTOCOL_VERSION;
        command.sequence = _helperSequence;
        command.page = index;
        command.width = (uint32_t)width;
        command.height = (uint32_t)height;
        command.priority = interactive ? PVRenderPriorityInteractive
                                       : PVRenderPriorityBackground;
        command.bytesPerRow = bytesPerRow;
        command.naturalWidth = _sizes[index].width;
        command.naturalHeight = _sizes[index].height;
        strlcpy(command.sharedMemoryName, name, sizeof(command.sharedMemoryName));

        BOOL wrote = PVWriteExact(_helperIn, &command, sizeof(command));
        PVRenderReply reply;
        memset(&reply, 0, sizeof(reply));
        BOOL timedOut = NO;
        double deadline = PVMonotonicSeconds() +
                          PVRenderDeadlineSeconds(width, height);
        BOOL readReply = wrote && PVReadExactUntil(_helperOut, &reply,
                                                   sizeof(reply), deadline,
                                                   &timedOut);
        BOOL wellFormed = (readReply &&
                           reply.magic == PV_RENDER_PROTOCOL_MAGIC &&
                           reply.version == PV_RENDER_PROTOCOL_VERSION &&
                           reply.sequence == command.sequence);
        BOOL succeeded = (wellFormed && reply.status == 0);

        if (!succeeded) {
            // A missed deadline, a protocol error and a dead helper are the same
            // situation: this helper can no longer be trusted to be at a message
            // boundary. Kill and reap it here; the next render starts a fresh
            // one. The kill happens before the mapping is dropped, so a helper
            // that was still writing is gone before the memory is.
            //
            // What differs between them is what the LAYER ABOVE should do, and
            // that is the whole point of reporting a reason rather than NULL: a
            // page Quartz will never draw has to stop being asked for, and a
            // page that lost a race with a killed helper has to be asked again.
            *failure = !wrote      ? PVRenderFailureProtocol
                     : timedOut    ? PVRenderFailureTimeout
                     : !readReply  ? PVRenderFailureProtocol
                     : !wellFormed ? PVRenderFailureProtocol
                                   : PVFailureForReplyStatus(reply.status);
            [self stopRenderHelper];
        } else {
            PVSharedBitmap *bitmap =
                (PVSharedBitmap *)calloc(1, sizeof(PVSharedBitmap));
            if (bitmap) {
                bitmap->address = map;
                bitmap->length = bytes;
                CGDataProviderRef provider = CGDataProviderCreateWithData(
                    bitmap, map, bytes, PVReleaseSharedBitmap);
                if (!provider) {
                    free(bitmap);
                } else {
                    // From here the provider owns the mapping: releasing it
                    // runs PVReleaseSharedBitmap, so this frame must not.
                    handed = YES;
                    CGColorSpaceRef colorSpace = CGColorSpaceCreateDeviceRGB();
                    if (colorSpace) {
                        image = CGImageCreate(width, height, 8, 32, bytesPerRow,
                            colorSpace,
                            (CGBitmapInfo)kCGImageAlphaNoneSkipFirst |
                                kCGBitmapByteOrder32Host,
                            provider, NULL, true, kCGRenderingIntentDefault);
                        CGColorSpaceRelease(colorSpace);
                    }
                    CGDataProviderRelease(provider);
                }
            }
            if (!image) *failure = PVRenderFailureTransientResource;

            // Retire this helper if it has served enough, or has just served
            // something large enough that its parse cache is the thing worth
            // dropping. Decided here, between renders, so the replacement is
            // started by the next call rather than in the middle of this one.
            if (++_helperRenders >= PV_HELPER_MAX_RENDERS ||
                (uint64_t)bytes >= PV_HELPER_LARGE_FRAME)
                retire = YES;
        }
    }
    @finally {
        shm_unlink(name);
        PVResidentSub(PVResidentRender, bytes);
        if (!handed) munmap(map, bytes);
        if (retire) [self stopRenderHelper];
    }
    return image;
}

